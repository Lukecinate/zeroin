//! Per-game starting belief about where a player's best sensitivity lies.
//!
//! The search starts from a mild prior centred on the player's current
//! sensitivity, combined with a population prior built offline from public
//! aggregate pro-settings statistics (median cm/360 and spread per title).
//! The table is a reviewed constant: it is never fetched at runtime.
//!
//! Sources (aggregate figures only, accessed 2026-11-11; see
//! `THIRD_PARTY_NOTICES.md`): SensLab "Pro Settings Statistics" (S1),
//! EsportSettings "Average Pro Settings by Game" (S2), CSDB.gg "What
//! Sensitivity Do CS2 Pros Use?" (S3, free with attribution), and Boudaoud et
//! al., CHI 2022 (S4) for the width check.

/// Population prior for one game, in cm/360 (hip-fire).
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct GamePrior {
    /// Game id (see [`crate::games`]).
    pub game_id: &'static str,
    /// Centre of the prior, cm/360.
    pub centre_cm: f64,
    /// Standard deviation in natural-log units.
    pub sd_log: f64,
    /// Source ids from the module docs.
    pub sources: &'static str,
}

/// Date the aggregate figures were read.
pub const DATA_DATE: &str = "2026-11-11";

/// Reviewed table (generated by the research script `build_priors.py`).
pub const PRIORS: &[GamePrior] = &[
    GamePrior { game_id: "valorant", centre_cm: 57.8, sd_log: 0.36, sources: "S1, S2" },
    GamePrior { game_id: "cs2", centre_cm: 51.3, sd_log: 0.307, sources: "S1, S2, S3" },
    GamePrior { game_id: "apex", centre_cm: 40.0, sd_log: 0.30, sources: "S1, S2" },
    GamePrior { game_id: "overwatch2", centre_cm: 35.4, sd_log: 0.373, sources: "S1" },
    GamePrior { game_id: "fortnite", centre_cm: 32.3, sd_log: 0.30, sources: "S1, S2" },
    GamePrior { game_id: "r6s", centre_cm: 40.5, sd_log: 0.30, sources: "S1" },
    GamePrior { game_id: "marvel_rivals", centre_cm: 39.1, sd_log: 0.332, sources: "S1" },
    GamePrior { game_id: "the_finals", centre_cm: 38.8, sd_log: 0.341, sources: "S1" },
    GamePrior { game_id: "cod", centre_cm: 42.2, sd_log: 0.329, sources: "S1 (small sample)" },
];

/// Prior for games without their own row (and custom games).
pub const UNKNOWN_GAME: GamePrior = GamePrior { game_id: "", centre_cm: 42.6, sd_log: 0.428, sources: "S1, S4" };

/// Prior for a game id; unknown ids get [`UNKNOWN_GAME`].
pub fn for_game(id: &str) -> GamePrior {
    PRIORS.iter().copied().find(|p| p.game_id == id).unwrap_or(UNKNOWN_GAME)
}

impl GamePrior {
    /// Centre of the prior on θ, the log change in degrees-per-count from the
    /// current setting. A slower population centre (more cm/360) gives a
    /// negative θ.
    pub fn theta_centre(&self, current_cm360: f64) -> f64 {
        (current_cm360 / self.centre_cm).ln()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_table_row_is_a_known_game() {
        for p in PRIORS {
            assert!(crate::games::by_id(p.game_id).is_some(), "{}", p.game_id);
            assert!(p.centre_cm > 10.0 && p.centre_cm < 100.0 && p.sd_log > 0.2 && p.sd_log < 0.6);
        }
        assert_eq!(for_game("nope"), UNKNOWN_GAME);
    }

    #[test]
    fn sign_of_theta() {
        let p = for_game("cs2");
        // Player at 25 cm/360 is faster than the centre: prior points to slowing down.
        assert!(p.theta_centre(25.0) < 0.0);
        assert!(p.theta_centre(100.0) > 0.0);
    }
}
